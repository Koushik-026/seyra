CREATE TRIGGER lab_update AFTER UPDATE ON lab_contacts FOR EACH ROW CALL 'planner.DbLab$ContactAudit';
CREATE TRIGGER lab_delete AFTER DELETE ON lab_contacts FOR EACH ROW CALL 'planner.DbLab$ContactAudit';
